from pydantic import BaseModel, Field
from typing import Annotated, Literal
from operator import add
from utils import llmpick

class AgentSchema(BaseModel):
    messages: Annotated[list, add] = Field(..., description="List of Message to be processed")
    user_ques : str = Field(..., description="User question to be processed by the agent")
    curated_ques : str = Field(..., description="Curated user question")
    prompt_query_context: str = Field(..., description="Detaild prompt with SQL DB context that will help agent to generate SQL Query")
    is_safe: Literal["Yes","No"] = Field(..., description="Indicates wheather the generated SQL query is safe")
    comments: str = Field(..., description="Additional comments or feedback from the judge regarding SQL query")
    generated_sql_query : str = Field(..., description="The SQL Query generated by the agent")
    sql_query_execution_result : str = Field(..., description="The result of executing the generated SQL Query")
    final_response : str = Field(..., description="The final response the agent based on the SQL Queryresponse")

# LLM AS JUDGE

class JudgeSchema(BaseModel):
    answer: Literal["Yes","No"] = Field(..., description="Indicates wheather the generated SQL query is safe to execute or not")
    comments: str = Field(...,description="Additional comments or feedback from the judge regarding SQL query")

class ETLAgentSchema(BaseModel):
    messages: Annotated[list,add] = Field(..., description = "List of messages processed by the ETL Agent" )

class RouterSchema(BaseModel):
    answer: Literal["sql", "etl", "pdf"] = Field(
        ...,
        description="Route to sql for database queries, etl for tabular data operations, or pdf for PDF extraction and analysis",
    )
    comments: str = Field(..., description = "Additional comments or feedback from the judge regarding the user question")


class WorkflowStepSchema(BaseModel):
    agent: Literal["sql", "etl", "pdf", "ui_automate"] = Field(
        description="Specialist agent to run at this step"
    )
    instruction: str = Field(
        description="Specific task for this agent, including relevant input/output requirements"
    )
    target_url: str | None = Field(
        default=None,
        description="Website URL for UI automation, if this step uses a website",
    )


class WorkflowPlanSchema(BaseModel):
    steps: list[WorkflowStepSchema] = Field(
        default_factory=list,
        max_length=4,
        description="Ordered list of distinct specialist agents needed for the request",
    )
    comments: str = Field(
        default="",
        description="Brief explanation of the planned workflow",
    )


class DataAgentSchema(BaseModel):
    messages: Annotated[list, add] = Field(
        default_factory=list,
        description="List of messages processed by the Data Agent",
    )
    route_response: RouterSchema | None = Field(
        default=None,
        description="The specialist selected by the router for the user question",
    )
    workflow_steps: list[WorkflowStepSchema] = Field(
        default_factory=list,
        description="Ordered specialist workflow selected by the planner",
    )
    current_step: int = Field(
        default=0,
        description="Index of the next workflow step to execute",
    )
    original_question: str = Field(
        default="",
        description="Original user request retained throughout the workflow",
    )
    artifacts: Annotated[list[dict[str, str]], add] = Field(
        default_factory=list,
        description="Files produced by specialist agents and available to later steps",
    )